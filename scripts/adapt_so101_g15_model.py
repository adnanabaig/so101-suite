"""Reproduce the documented G15 operating-range adaptation after model vendoring."""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path

UPSTREAM_SHA256 = "982c02c027ec0c62d3459d0a6eb00dfb7dc13a451992e72ce99addc71f209805"
ADAPTED_SHA256 = "c4fa9c36342e983af848ed278973824766b4911ccebafc820bf7c9b6cd3efa86"
REPLACEMENTS = (
    (
        b'name="shoulder_lift" type="hinge" range="-1.7453293 1.7453293"',
        b'name="shoulder_lift" type="hinge" range="-1.7627825445142729 1.7453293"',
    ),
    (
        b'name="elbow_flex" type="hinge" range="-1.69 1.69"',
        b'name="elbow_flex" type="hinge" range="-1.69 1.7278759594743862"',
    ),
    (
        b'name="shoulder_lift" joint="shoulder_lift" ctrlrange="-1.74533 1.74533"',
        b'name="shoulder_lift" joint="shoulder_lift" ctrlrange="-1.7627825445142729 1.74533"',
    ),
    (
        b'name="elbow_flex" joint="elbow_flex" ctrlrange="-1.69 1.69"',
        b'name="elbow_flex" joint="elbow_flex" ctrlrange="-1.69 1.7278759594743862"',
    ),
)
ADAPTATION_NOTE = """## G15 compact-rest range adaptation (2026-10-27)

The local `so101.xml` changes exactly four joint/actuator range attributes:
shoulder minimum -101 degrees (maximum +100 unchanged), elbow maximum +99
degrees (minimum unchanged). These implement the documented G15 software
operating envelope, not manufacturer limits or proof of physical clearance.
Offsets, joint frames, meshes and inertias are unchanged. The dynamics proof
above applies to the base mesh conversion before this range adaptation.

Reproduce the combined model and manifest with
`python scripts/vendor_so101_model.py --source <source> --g15-operating-ranges`;
add `--check` to compare the complete adapted tree. The standalone
`python scripts/adapt_so101_g15_model.py --check` checks both XML and manifest.
Neither tool changes robot calibration or motor registers.
"""


def adapt(data: bytes) -> bytes:
    digest = hashlib.sha256(data).hexdigest()
    if digest == ADAPTED_SHA256:
        return data
    if digest != UPSTREAM_SHA256:
        raise ValueError("Model differs from the pinned upstream and G15 adaptation; refusing")
    for original, replacement in REPLACEMENTS:
        if data.count(original) != 1:
            raise ValueError("Expected exactly one joint/actuator range")
        data = data.replace(original, replacement, 1)
    if hashlib.sha256(data).hexdigest() != ADAPTED_SHA256:
        raise ValueError("Adapted model digest does not match the reviewed G15 model")
    return data


def adapt_provenance(text: str) -> str:
    row = re.search(r"^\| `so101.xml` \| (copied|adapted) \|.*$", text, re.M)
    if row is None or UPSTREAM_SHA256 not in row[0]:
        raise ValueError("Missing pinned upstream model provenance")
    was_base = row[1] == "copied"
    expected = UPSTREAM_SHA256 if was_base else ADAPTED_SHA256
    if not row[0].endswith(f"`{expected}` |"):
        raise ValueError("Unexpected model output hash in provenance")
    text = (
        text[: row.start()]
        + (
            "| `so101.xml` | adapted | - | 17,206 -> 17,254 | "
            f"`{UPSTREAM_SHA256}` | `{ADAPTED_SHA256}` |"
        )
        + text[row.end() :]
    )
    text = text.split("## G15 compact-rest range adaptation", 1)[0].rstrip() + "\n"
    text = (
        "# Provenance: `robotstudio_so101`\n\n"
        "Base conversion generated by `scripts/vendor_so101_model.py`, followed by\n"
        "`scripts/adapt_so101_g15_model.py`. Input/output hashes distinguish the\n"
        "upstream model from the G15 operating-range adaptation.\n\n"
        + text[text.index("| Field | Value |") :]
    )
    text = re.sub(
        r"1\. `so101.xml`.*?(?=\n2\.)",
        "1. `scene.xml`, `scene_box.xml` and `LICENSE` are byte-exact copies.\n"
        "   `so101.xml` has the four G15 joint/actuator range changes below.\n"
        "   Other runtime changes use `mujoco.MjSpec` in memory.",
        text,
        count=1,
        flags=re.S,
    )
    if was_base:
        text = re.sub(
            r"([\d,]+) bytes vendored",
            lambda match: f"{int(match[1].replace(',', '')) + 48:,} bytes vendored",
            text,
            count=1,
        )
    text = text.replace(
        "## Dynamics equivalence\n", "## Dynamics equivalence (base mesh conversion)\n"
    )
    return text.rstrip() + "\n\n" + ADAPTATION_NOTE


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--model",
        type=Path,
        default=Path(__file__).resolve().parents[1]
        / "src/so101/simulation/assets/robotstudio_so101/so101.xml",
    )
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    data = args.model.read_bytes()
    adapted = adapt(data)
    provenance_path = args.model.with_name("PROVENANCE.md")
    provenance = provenance_path.read_text()
    adapted_manifest = adapt_provenance(provenance)
    if args.check and (data != adapted or provenance != adapted_manifest):
        parser.error("Model or manifest does not match the G15 range adaptation")
    if not args.check and data != adapted:
        args.model.write_bytes(adapted)
    if not args.check and provenance != adapted_manifest:
        provenance_path.write_text(adapted_manifest)
    print(f"G15 model verified: {ADAPTED_SHA256}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
